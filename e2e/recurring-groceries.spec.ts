import { test, expect } from '@playwright/test';

test('usual groceries explicitly populate selected weeks and retain old shopping snapshots', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/register');
  await page.locator('#email').fill(`usual-${Date.now()}-${Math.random()}@example.com`);
  await page.locator('#password').fill('family-password123');
  await page.locator('#confirmPassword').fill('family-password123');
  await page.getByRole('button', { name: 'Create Account' }).click();
  await expect(page).toHaveURL('/week');
  await page.goto('/shopping?week=2026-10-12');
  await page.getByRole('button', { name: 'Usual groceries', exact: true }).click();
  await page.getByLabel('Usual item', { exact: true }).fill('Milk');
  await page.getByLabel('Usual amount (optional)', { exact: true }).fill('1 carton');
  await page.getByRole('button', { name: 'Save usual grocery', exact: true }).click();
  await page.getByLabel('Add usual Milk', { exact: true }).check();
  await expect(page.getByText('1 carton Milk', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await testInfo.attach('usual-groceries-phone', { body: await page.screenshot(), contentType: 'image/png' });
  await page.getByRole('button', { name: 'Add selected to this week (1)', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Purchased Milk', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await testInfo.attach('usual-groceries-applied-phone', { body: await page.screenshot(), contentType: 'image/png' });
  const oldWeek = (await (await page.request.get('/api/plans/2026-10-12')).json());
  const oldId = oldWeek.shopping[0].id;
  await page.getByRole('checkbox', { name: 'Purchased Milk', exact: true }).check();
  await expect(page.getByRole('button', { name: 'Usual groceries', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Usual groceries', exact: true }).click();
  await page.getByRole('button', { name: 'Edit usual Milk', exact: true }).click();
  await page.getByLabel('Usual item', { exact: true }).fill('Oat milk');
  await page.getByLabel('Usual amount (optional)', { exact: true }).fill('2 cartons');
  await page.getByRole('button', { name: 'Save usual changes', exact: true }).click();
  await page.getByLabel('Add usual Oat milk', { exact: true }).check();
  await page.getByRole('button', { name: 'Add selected to this week (1)', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Usual groceries', exact: true })).toBeEnabled();
  const preserved = await (await page.request.get('/api/plans/2026-10-12')).json();
  expect(preserved.shopping).toHaveLength(1);
  expect(preserved.shopping[0]).toMatchObject({ id: oldId, ingredient: 'Milk', amount: '1 carton', state: 'bought' });
  await page.goto('/shopping?week=2026-10-19');
  await expect(page.getByText(/Add recipes to your week/)).toBeVisible();
  await page.getByRole('button', { name: 'Usual groceries', exact: true }).click();
  await page.getByLabel('Add usual Oat milk', { exact: true }).check();
  await page.getByRole('button', { name: 'Add selected to this week (1)', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Purchased Oat milk', exact: true })).not.toBeChecked();
  await page.reload();
  await expect(page.getByRole('checkbox', { name: 'Purchased Oat milk', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Usual groceries', exact: true }).click();
  await page.getByRole('button', { name: 'Delete usual Oat milk', exact: true }).click();
  await expect(page.getByText('No saved groceries yet.')).toBeVisible();
  await page.getByRole('button', { name: 'Close Usual groceries' }).click();
  await expect(page.getByRole('checkbox', { name: 'Purchased Oat milk', exact: true })).toBeVisible();
  await page.goto('/shopping?week=2026-10-12');
  await expect(page.getByRole('checkbox', { name: 'Purchased Milk', exact: true })).toBeVisible();
  await expect(page.getByRole('checkbox', { name: 'Purchased Milk', exact: true })).toBeChecked();
  expect((await (await page.request.get('/api/plans/2026-10-12')).json()).shopping[0].id).toBe(oldId);
});
