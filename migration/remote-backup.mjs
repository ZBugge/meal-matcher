// Explicit read-only administrative D1 export. Never loaded by the application.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { exportFull, writeFullBackup } from './full-backup.mjs';
import { releaseTarget } from '../scripts/release-target.mjs';
import { privateDirectory } from '../scripts/local-paths.mjs';

export function readonlyD1({ accountId, databaseId, token, transport = fetch, intervalMs = 260 }) {
  if (!/^[a-f0-9]{32}$/.test(accountId) || !/^[a-f0-9-]{36}$/.test(databaseId) || !token) throw new Error('Explicit provider account, database and scoped token required');
  let previous = 0;
  const query = async (sql, params) => {
    // Only these statements are generated by the reviewed exporter. No remote
    // restore, schema command, mutation or user-provided SQL is exposed here.
    const pagedRead = sql.startsWith('WITH "__full_backup_candidates" AS MATERIALIZED (SELECT ') && !/\b(?:INSERT|UPDATE|DELETE|DROP|ALTER|CREATE|REPLACE|ATTACH|DETACH|VACUUM|REINDEX|ANALYZE|PRAGMA)\b/i.test(sql);
    if (sql.includes(';') || (!pagedRead && !/^SELECT\s/i.test(sql) && !/^PRAGMA\s+(?:table_xinfo|foreign_key_list)\(/i.test(sql) && sql !== 'PRAGMA foreign_key_check')) throw new Error('Remote backup adapter is read-only');
    const delay = Math.max(0, previous + intervalMs - Date.now());
    if (delay) await new Promise(resolve => setTimeout(resolve, delay));
    previous = Date.now();
    const response = await transport(`https://api.cloudflare.com/client/v4/accounts/${accountId}/d1/database/${databaseId}/query`, {
      method: 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ sql, params }), signal: AbortSignal.timeout(15000), redirect: 'error',
    });
    const payload = await response.json();
    if (!response.ok || payload.success !== true || !Array.isArray(payload.result) || payload.result.length !== 1 || payload.result[0].success !== true || !Array.isArray(payload.result[0].results)) throw new Error('Private D1 read failed; no export can be accepted');
    return payload.result[0];
  };
  return {
    prepare(sql) {
      let params = [];
      return { bind(...values) { params = values; return this; }, all() { return query(sql, params); }, async run() { throw new Error('Remote backup adapter cannot mutate'); } };
    },
    async batch() { throw new Error('Remote backup adapter cannot mutate or restore'); },
  };
}

export async function remoteBackup({ environment, output, source, quiesced, root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), transport = fetch }) {
  if (quiesced !== true) throw new Error('Pause ALL writers including session touches/cleanup before exporting; explicit --quiesced required');
  const config = JSON.parse(await readFile(path.join(root, 'wrangler.jsonc'), 'utf8'));
  const targets = JSON.parse(await readFile(path.join(root, 'cloudflare/targets.json'), 'utf8'));
  const target = releaseTarget(config, targets, environment, process.env.CLOUDFLARE_ACCOUNT_ID);
  if (!output || !source) throw new Error('Explicit private output file and opaque source label required');
  const filename = path.resolve(output);
  const relative = path.relative(root, filename);
  if (!relative.startsWith('.verification' + path.sep) || relative.startsWith('..')) throw new Error('Export must stay in ignored private checkout .verification/');
  await privateDirectory(root, path.dirname(filename));
  console.log(JSON.stringify({ readOnlyExport: true, environment, worker: target.worker, database: target.database, databaseId: target.databaseId }));
  const db = readonlyD1({ accountId: target.accountId, databaseId: target.databaseId, token: process.env.CLOUDFLARE_API_TOKEN, transport });
  const backup = await exportFull(db, { source, quiesced });
  await writeFullBackup(filename, backup);
  const backupSha256 = createHash('sha256').update(await readFile(filename)).digest('hex');
  const manifest = { verified: true, environment, databaseId: target.databaseId, source, backupSha256, createdAt: new Date().toISOString(), tables: backup.tables.length, schemaSha256: backup.schemaSha256, scope: 'full-runtime-portable', quiescence: 'Caller confirms all writers stopped; export comparison is not a database snapshot lock' };
  await writeFile(filename + '.manifest.json', JSON.stringify(manifest, null, 2), { flag: 'wx' });
  return manifest;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2), options = {};
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--quiesced') options.quiesced = true;
    else if (['--env', '--output', '--source'].includes(args[i]) && args[i + 1]) options[args[i].slice(2)] = args[++i];
    else throw new Error('Use --env staging|production --output <new-private-file> --source <opaque-label> --quiesced');
  }
  remoteBackup({ ...options, environment: options.env }).then(manifest => console.log(JSON.stringify(manifest))).catch(() => { console.error('Private export failed; preserve source and any output. Do not accept an incomplete backup.'); process.exitCode = 1; });
}
